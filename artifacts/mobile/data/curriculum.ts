export type NodeType = "theory" | "miniQuiz" | "practice" | "boss";

export interface Question {
  id: string;
  text: string;
  options: string[];
  correct: string;
  explanation: string;
}

export interface LessonNode {
  id: string;
  chapterId: string;
  type: NodeType;
  label: string;
  iconName: string;
  theoryTitle?: string;
  theoryContent?: string;
  theoryKeyPoints?: string[];
  videoUrl?: string;
  questions?: Question[];
  xpReward: number;
}

export interface Chapter {
  id: string;
  title: string;
  description: string;
  iconName: string;
  color: string;
  nodes: LessonNode[];
}

const q = (
  id: string,
  text: string,
  options: string[],
  correct: string,
  explanation: string
): Question => ({ id, text, options, correct, explanation });

function theoryNode(
  chapterId: string,
  id: string,
  title: string,
  content: string,
  keyPoints: string[],
  xpReward = 10,
  videoUrl?: string
): LessonNode {
  return {
    id,
    chapterId,
    type: "theory",
    label: "Теория",
    iconName: "book-open",
    theoryTitle: title,
    theoryContent: content,
    theoryKeyPoints: keyPoints,
    ...(videoUrl ? { videoUrl } : {}),
    xpReward,
  };
}

function activityNode(
  chapterId: string,
  id: string,
  type: "miniQuiz" | "practice" | "boss",
  label: string,
  iconName: string,
  questions: Question[],
  xpReward: number
): LessonNode {
  return { id, chapterId, type, label, iconName, questions, xpReward };
}

